-- Autostart daemons inside the UWSM systemd scope
hl.on("hyprland.start", function()
    -- Re-import Hyprland-set env (HYPRLAND_INSTANCE_SIGNATURE, etc.) into the
    -- systemd user manager so uwsm-app scopes and `hyprctl` from terminals work.
    hl.dispatch(
        hl.dsp.exec_cmd(
            "systemctl --user import-environment HYPRLAND_INSTANCE_SIGNATURE WAYLAND_DISPLAY XDG_CURRENT_DESKTOP"
        )
    )
    hl.dispatch(
        hl.dsp.exec_cmd(
            "dbus-update-activation-environment --systemd HYPRLAND_INSTANCE_SIGNATURE WAYLAND_DISPLAY XDG_CURRENT_DESKTOP"
        )
    )

    hl.dispatch(hl.dsp.exec_cmd("uwsm app -- swaync"))
    hl.dispatch(hl.dsp.exec_cmd("systemctl --user start hyprpolkitagent"))
    hl.dispatch(hl.dsp.exec_cmd("uwsm app -- hypridle"))
    hl.dispatch(hl.dsp.exec_cmd("uwsm app -- hyprpaper"))

    -- create the headless output before sunshine reads output_name
    hl.dispatch(hl.dsp.exec_cmd("sh -c 'hyprctl output create headless; systemctl --user start sunshine'"))
end)

