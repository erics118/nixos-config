    left = "l",
    right = "r",
    up = "u",
    down = "d",
    h = "l",
    l = "r",
    k = "u",
    j = "d",
}) do
    hl.bind(mod .. " + " .. k, hl.dsp.focus({ direction = dir }))
end

-- move window
for k, dir in pairs({ left = "l", right = "r", up = "u", down = "d" }) do
    hl.bind(mod .. " + SHIFT + " .. k, hl.dsp.window.move({ direction = dir })) -- inferred API
end

-- resize (repeats while held)
local rep = { repeating = true }
for k, delta in pairs({ left = { -40, 0 }, right = { 40, 0 }, up = { 0, -40 }, down = { 0, 40 } }) do
    hl.bind(mod .. " + ALT + " .. k, hl.dsp.window.resize({ x = delta[1], y = delta[2] }), rep)
end

